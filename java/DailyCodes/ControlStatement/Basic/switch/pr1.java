class SwitchDemo{
	public static void main (String []args){
		char num =50;
		System.out.println("Before switch");

		switch(num){
			case 20==30:{
				System.out.println("one");
				break;
			}

			case 25+25:{
				       System.out.println("two");
				       break;
			}
			case 50:{
				       System.out.println("three");
				       break;
			}
		}
		System.out.println("After switch");
	}

}
